function normalizeSuggestionText(value = "") {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function suggestEmarqetCategory(value = "") {
  const normalized = normalizeSuggestionText(value);
  if (normalized.length < 4) return null;
  const text = ` ${normalized} `;
  const scored = EMARQET_CATEGORY_SUGGESTION_RULES.map((rule) => {
    const matches = rule.keywords
      .map(normalizeSuggestionText)
      .filter((keyword) => keyword && text.includes(` ${keyword} `));
    const score = matches.reduce((total, keyword) => {
      if (keyword.includes(" ")) return total + 4;
      return total + (keyword.length >= 6 ? 2 : 1);
    }, 0);
    return { code: rule.code, score, matches };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || b.matches.join("").length - a.matches.join("").length);
  return scored[0]?.score >= 2 ? scored[0] : null;
}
